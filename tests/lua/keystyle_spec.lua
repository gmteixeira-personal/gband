local t = require("gband.test")

t.case("the direct style's mode letter and key list title", function(g)
  g.start({ keystyle = "direct" })
  g.wait_text("$")
  g.keys("ctrl+space")
  g.settle()
  t.match(g.screen().row(0), "^P")
  g.keys("?")
  g.settle()
  t.match(g.screen().text(), "prefix keys")
  g.expect_screenshot("direct")
end)

local function reloaded_by(g, keys)
  g.client("reload_marker = true")
  for _, key in ipairs(keys) do
    g.keys(key)
    g.settle()
  end
  t.eq(g.client("return reload_marker"), nil)
  t.eq(g.client("return gband.keymap.current_table()"), "root")
  t.eq(g.client("return gband.view().plugin_window"), nil)
end

t.case("prefix ! reloads with the modal style, also mid navigation", function(g)
  g.start({ keystyle = "modal" })
  g.wait_text("$")
  reloaded_by(g, { "ctrl+space !" })
  reloaded_by(g, { "ctrl+space n", "h", "!" })
end)

t.case("prefix ! reloads with the direct style", function(g)
  g.start({ keystyle = "direct" })
  g.wait_text("$")
  reloaded_by(g, { "ctrl+space !" })
end)

t.case("prefix ! reloads from the floating window list", function(g)
  g.start({ files = { ["user/keystyle.lua"] = 'return "floating"\n' } })
  g.wait_text("$")
  reloaded_by(g, { "ctrl+space", "!" })
end)

t.case("! in the key list reloads with the modal style", function(g)
  g.start({ keystyle = "modal" })
  g.wait_text("$")
  reloaded_by(g, { "ctrl+space ?", "!" })
end)

t.case("! in the key list reloads with the floating style", function(g)
  g.start({ files = { ["user/keystyle.lua"] = 'return "floating"\n' } })
  g.wait_text("$")
  reloaded_by(g, { "ctrl+space", "?", "!" })
end)

local BROKEN_SERVER = "error('first', 0)"

local function plugin_window(g)
  return g.client("return gband.view().plugin_window")
end

t.case("prefix e lists the errors from navigation mode", function(g)
  g.start({ keystyle = "modal", server_config = BROKEN_SERVER })
  g.wait_text("$")
  g.keys("ctrl+space e")
  g.settle()
  t.ok(plugin_window(g), "the error list is focused")
  t.ok(g.screen().text():find("errors  c clear", 1, true), "the list is titled with its hint")
  t.ok(g.screen().text():find("server: first", 1, true), "the list shows the error")
  t.eq(g.client("return gband.keymap.current_table()"), "root")
end)

t.case("prefix E clears the errors and stays in navigation mode", function(g)
  g.start({ keystyle = "modal", server_config = BROKEN_SERVER })
  g.wait_text("$")
  t.eq(g.client("return #gband.errors()"), 1)
  g.keys("ctrl+space E")
  g.settle()
  t.eq(g.client("return gband.errors()"), {})
  t.eq(plugin_window(g), nil)
  t.eq(g.client("return gband.keymap.current_table()"), "prefix")
end)

t.case("prefix E then prefix e with the direct style", function(g)
  g.start({ keystyle = "direct", server_config = BROKEN_SERVER })
  g.wait_text("$")
  g.keys("ctrl+space E")
  g.settle()
  t.eq(g.client("return gband.keymap.current_table()"), "root")
  g.keys("ctrl+space e")
  g.settle()
  t.ok(plugin_window(g), "the error list is focused")
  t.ok(g.screen().text():find("no errors", 1, true), "the list shows no errors")
end)

t.case("prefix e and E without the error list plugin", function(g)
  g.start({ config = [[gband.keystyle.use("modal")]], server_config = BROKEN_SERVER })
  g.wait_text("$")
  local before = g.screen().text()
  g.keys("ctrl+space e E")
  g.settle()
  t.eq(plugin_window(g), nil)
  t.eq(g.client("return gband.errors()"), { "server: first" })
  t.eq(g.client("return gband.keymap.current_table()"), "prefix")
  t.eq(g.screen().text(), before)
end)

t.case("error list set up after the preset", function(g)
  g.start({
    config = [[
gband.keystyle.use("modal")
gband.plugin("gband.errors", { kind = "tiled" })
]],
  })
  g.wait_text("$")
  g.keys("ctrl+space e")
  g.settle()
  local win = plugin_window(g)
  t.ok(win, "the error list is focused")
  t.eq(g.client("return gband.win.info(...).kind", win), "tiled")
end)
