local t = require("gband.test")

t.case("the chooser fits beside the default status line on the first start", function(g)
  g.start({ keystyle = false })
  g.wait_text("$")
  g.keys("down up")
  g.settle()
  t.eq(g.client("return #gband.win.list()"), 1)
  t.match(g.screen().row(1), "^C%-space navigation")
  t.match(g.screen().row(10), "^ +│┌key style  enter choose  esc later.-┐$")
  t.match(g.screen().row(11), "^ +││modal   C%-space enters a mode, keys repeat until Escape│")
  t.match(g.screen().row(12), "^ +││direct  C%-space then one key per action, back to typing│")
  g.expect_screenshot("first-start")
end)

t.case("the direct style's hints and key list title", function(g)
  g.start({ keystyle = "direct" })
  g.wait_text("$")
  t.match(g.screen().row(1), "^C%-space prefix")
  g.keys("ctrl+space ?")
  g.settle()
  t.match(g.screen().text(), "prefix keys")
  g.expect_screenshot("direct")
end)
