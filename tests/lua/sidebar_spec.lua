t.case("the floating style shows the apps character", function(g)
  g.start({ size = "40x8", files = { ["user/keystyle.lua"] = 'return "floating"\n' } })
  prompts(g, 1)
  t.eq(column(g.screen()), "∷ 12─")
  t.ok(g.screen().cell(0, 0).bold)
  g.keys("ctrl+space")
  g.settle()
  t.eq(g.screen().cell(0, 0).char, "∷")
  g.keys("escape")
  g.settle()
  g.expect_screenshot("apps")
end)

t.case("click the apps character", function(g)
  g.start({ files = { ["user/keystyle.lua"] = 'return "floating"\n' } })
  prompts(g, 1)
  g.client("gband.action.open_window({ floating = true })")
  g.settle()
  g.client("gband.window.rename(1, 'notes') gband.window.rename(2, 'logs')")
  g.client("gband.window.focus(1)")
  g.settle()
  g.client("gband.window.focus(2)")
  g.settle()
  prompts(g, 2)
  g.mouse("press", "left", 0, 0)
  g.mouse("release", "left", 0, 0)
  g.settle()
  local focused = g.client("return gband.view().plugin_window")
  t.ok(focused)
  local info = g.client("return gband.win.info(...)", focused)
  t.eq({ info.col, info.row, info.width, info.height }, { 27, 8, 24, 8 })
  t.match(g.screen().row(8), "┌windows")
  for offset, text in ipairs({ "│ n New window", "│ s Settings", "│ m Multi mode", "├───", "│ 1 logs", "│ 2 notes" }) do
    t.ok(g.screen().row(8 + offset):find(text, 1, true), text)
  end
  t.eq(g.client("return gband.keymap.current_table()"), "root")
  g.expect_screenshot("window list")
end)

